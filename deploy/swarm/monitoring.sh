#!/usr/bin/env bash
# The optional monitoring profile of the swarm stack. Sourced by stack.sh; not run on its own.
#
#   MONITORING=1   Prometheus and Alertmanager as services on the Manager, with the rules of deploy/monitoring/rusty.rules.yml. Prometheus scrapes ONE target, the admin web's central endpoint (it reads
#                  the /metrics of every other service), over the internal `metrics` network; nothing is published. Alertmanager sends what fires to a webhook (or a Slack-compatible one), over `backend`
#                  (the network that has a way out).
#
#   ALERT_URL_FILE  a file with the URL alerts are posted to (one line). It is a Docker secret: the URL of a chat webhook carries a token. Required.
#   ALERT_KIND      webhook (default: Alertmanager's JSON, for ntfy, Gotify, a bridge of yours...) or slack (Slack, and chats that take a Slack incoming webhook: Mattermost, Discord's /slack, Rocket.Chat)
#                   or email: ALERT_EMAIL_TO, ALERT_EMAIL_FROM and ALERT_SMARTHOST (host:port of a mail server that takes the alerts, STARTTLS required unless ALERT_SMTP_TLS=0); with a login, ALERT_SMTP_USER and
#                   ALERT_SMTP_PASSWORD_FILE (a Docker secret). ALERT_URL_FILE is not used then. Do not point it at the mail server this stack runs if that is what has failed.
#   ALERT_REPEAT    how often a firing alert is repeated: 30m, 4h ... (default 4h)
#   PROM_RETENTION  how long Prometheus keeps its samples (default 30d)

MONITORING="${MONITORING:-0}"
ALERT_URL_FILE="${ALERT_URL_FILE:-}"
ALERT_KIND="${ALERT_KIND:-webhook}"
ALERT_REPEAT="${ALERT_REPEAT:-4h}"
ALERT_EMAIL_TO="${ALERT_EMAIL_TO:-}"
ALERT_EMAIL_FROM="${ALERT_EMAIL_FROM:-}"
ALERT_SMARTHOST="${ALERT_SMARTHOST:-}"
ALERT_SMTP_USER="${ALERT_SMTP_USER:-}"
ALERT_SMTP_PASSWORD_FILE="${ALERT_SMTP_PASSWORD_FILE:-}"
ALERT_SMTP_TLS="${ALERT_SMTP_TLS:-1}"
PROM_RETENTION="${PROM_RETENTION:-30d}"

monitoring_check_inputs() {
  case "$MONITORING" in 0|1) ;; *) die "MONITORING is 0 or 1" ;; esac
  case "$ALERT_KIND" in webhook|slack|email) ;; *) die "ALERT_KIND is webhook, slack or email" ;; esac
  [[ "$ALERT_REPEAT" =~ ^[1-9][0-9]*[mh]$ ]] || die "ALERT_REPEAT is a number of minutes or hours: 30m, 4h"
  [[ "$PROM_RETENTION" =~ ^[1-9][0-9]*[dwy]$ ]] || die "PROM_RETENTION is a number of days, weeks or years: 30d, 12w"
  [ "$MONITORING" = 1 ] || return 0
  if [ "$ALERT_KIND" = email ]; then
    [[ "$ALERT_EMAIL_TO" =~ ^[^[:space:]@,\'\"]+@[A-Za-z0-9.-]+$ ]] || die "ALERT_KIND=email needs ALERT_EMAIL_TO: one address"
    [[ "$ALERT_EMAIL_FROM" =~ ^[^[:space:]@,\'\"]+@[A-Za-z0-9.-]+$ ]] || die "ALERT_KIND=email needs ALERT_EMAIL_FROM: one address"
    [[ "$ALERT_SMARTHOST" =~ ^[A-Za-z0-9.-]+:[0-9]{1,5}$ ]] || die "ALERT_KIND=email needs ALERT_SMARTHOST: host:port of the mail server that sends the alerts (for example mail.example.org:587)"
    [[ "$ALERT_SMTP_USER" =~ ^[^[:space:]\'\"]*$ ]] || die "ALERT_SMTP_USER has a character that does not belong in a login"
    case "$ALERT_SMTP_TLS" in 0|1) ;; *) die "ALERT_SMTP_TLS is 1 (the default: the server must offer STARTTLS) or 0" ;; esac
    [ -z "$ALERT_SMTP_PASSWORD_FILE" ] || { [ -s "$ALERT_SMTP_PASSWORD_FILE" ] && [ -r "$ALERT_SMTP_PASSWORD_FILE" ]; } || die "ALERT_SMTP_PASSWORD_FILE $ALERT_SMTP_PASSWORD_FILE is not a readable, non-empty file"
    [ -z "$ALERT_SMTP_USER" ] || [ -n "$ALERT_SMTP_PASSWORD_FILE" ] || die "ALERT_SMTP_USER needs ALERT_SMTP_PASSWORD_FILE"
    return 0
  fi
  [ -n "$ALERT_URL_FILE" ] || die "MONITORING=1 needs ALERT_URL_FILE: a file with the URL the alerts are posted to"
  [ -s "$ALERT_URL_FILE" ] && [ -r "$ALERT_URL_FILE" ] || die "ALERT_URL_FILE $ALERT_URL_FILE is not a readable, non-empty file"
  [[ "$(head -1 "$ALERT_URL_FILE")" =~ ^https?://[^[:space:]]+$ ]] || die "ALERT_URL_FILE must hold one http:// or https:// URL"
}

conf_prometheus() {
  cat <<'EOF'
# Generated by deploy/swarm/monitoring.sh. One target (by `tasks.`: through the service address the network would rewrite the source, and the admin web lets only Prometheus' own address in): the admin web's central endpoint, which serves the samples of every service (labelled `service` and `instance`).
global:
  scrape_interval: 30s
  evaluation_interval: 30s
rule_files:
  - /etc/prometheus/rusty.rules.yml
alerting:
  alertmanagers:
    - static_configs:
        - targets: ["alertmanager:9093"]
scrape_configs:
  - job_name: rusty
    honor_labels: true
    static_configs:
      - targets: ["tasks.admin:9100"]
EOF
}

conf_alertmanager() {
  if [ "$ALERT_KIND" = email ]; then
    printf 'global:\n  smtp_smarthost: "%s"\n  smtp_from: "%s"\n  smtp_require_tls: %s\n' "$ALERT_SMARTHOST" "$ALERT_EMAIL_FROM" "$([ "$ALERT_SMTP_TLS" = 1 ] && echo true || echo false)"
    [ -z "$ALERT_SMTP_USER" ] || printf '  smtp_auth_username: "%s"\n  smtp_auth_password_file: /run/secrets/alert_smtp\n' "$ALERT_SMTP_USER"
  fi
  cat <<EOF
# Generated by deploy/swarm/monitoring.sh. The URL (or the mail password) is in a secret, never in this file.
route:
  receiver: ops
  group_by: [alertname]
  group_wait: 30s
  group_interval: 5m
  repeat_interval: $ALERT_REPEAT
receivers:
  - name: ops
EOF
  if [ "$ALERT_KIND" = email ]; then
    printf '    email_configs:\n      - to: "%s"\n        send_resolved: true\n' "$ALERT_EMAIL_TO"
  elif [ "$ALERT_KIND" = slack ]; then
    printf '    slack_configs:\n      - api_url_file: /run/secrets/alert_url\n        send_resolved: true\n'
  else
    printf '    webhook_configs:\n      - url_file: /run/secrets/alert_url\n        send_resolved: true\n'
  fi
}

monitoring_secrets() {
  [ "$MONITORING" = 1 ] || return 0
  if [ "$ALERT_KIND" = email ]; then
    [ -z "$ALERT_SMTP_PASSWORD_FILE" ] || ensure_secret alert_smtp "$ALERT_SMTP_PASSWORD_FILE"
  else
    ensure_secret alert_url "$ALERT_URL_FILE"
  fi
}

monitoring_configs() {
  [ "$MONITORING" = 1 ] || return 0
  local d="$STATE_DIR/stack/etc"
  ( umask 077; conf_prometheus > "$d/prometheus.yml"; conf_alertmanager > "$d/alertmanager.yml" )
  ensure_config prom_conf "$d/prometheus.yml"
  ensure_config prom_rules "$HERE/../monitoring/rusty.rules.yml"
  ensure_config am_conf "$d/alertmanager.yml"
}

monitoring_names_needed() {
  [ "$MONITORING" = 1 ] || return 0
  if [ "$ALERT_KIND" != email ]; then printf 'S alert_url\n'; elif [ -n "$ALERT_SMTP_PASSWORD_FILE" ]; then printf 'S alert_smtp\n'; fi
  printf 'C prom_conf\nC prom_rules\nC am_conf\n'
}

monitoring_volumes() { printf '  prom_data:\n  am_data:\n'; }

# Prometheus and Alertmanager run as `nobody` (65534): a new named volume belongs to root, so it is handed over before the stack is deployed (a throw-away root container with the CHOWN capability only).
monitoring_prepare_volumes() {
  local v
  [ "$MONITORING" = 1 ] || return 0
  for v in prom_data am_data; do
    sw volume create --label "com.docker.stack.namespace=$STACK_NAME" "${STACK_NAME}_$v" >/dev/null
    sw run --rm --user 0 --cap-drop ALL --cap-add CHOWN --entrypoint chown -v "${STACK_NAME}_$v:/v" "$(lock_ref 'curlimages/curl:8.15.0')" 65534:65534 /v \
      || die "the volume ${STACK_NAME}_$v could not be handed to the monitoring user"
  done
}

gen_monitoring_services() {
  y_service_common prometheus "$(lock_ref 'prom/prometheus:v3.9.1')"
  printf '      - prom_data:/prometheus\n    user: "65534:65534"\n'
  printf '    command: ["--config.file=/etc/prometheus/prometheus.yml", "--storage.tsdb.path=/prometheus", "--storage.tsdb.retention.time=%s"]\n' "$PROM_RETENTION"
  y_deploy 1 "node.role == manager" stop-first prometheus
  printf '    configs:\n'
  y_config prom_conf /etc/prometheus/prometheus.yml
  y_config prom_rules /etc/prometheus/rusty.rules.yml
  printf '    healthcheck:\n      test: ["CMD", "/bin/wget", "-q", "--spider", "http://127.0.0.1:9090/-/healthy"]\n      interval: 30s\n      timeout: 5s\n      retries: 5\n      start_period: 30s\n    networks:\n      - metrics\n'
  y_service_common alertmanager "$(lock_ref 'prom/alertmanager:v0.28.1')"
  printf '      - am_data:/alertmanager\n    user: "65534:65534"\n'
  y_deploy 1 "node.role == manager" stop-first alertmanager
  if [ "$ALERT_KIND" != email ]; then
    printf '    secrets:\n'
    y_secret alert_url alert_url 65534
  elif [ -n "$ALERT_SMTP_PASSWORD_FILE" ]; then
    printf '    secrets:\n'
    y_secret alert_smtp alert_smtp 65534
  fi
  printf '    configs:\n'
  y_config am_conf /etc/alertmanager/alertmanager.yml
  printf '    healthcheck:\n      test: ["CMD", "/bin/wget", "-q", "--spider", "http://127.0.0.1:9093/-/healthy"]\n      interval: 30s\n      timeout: 5s\n      retries: 5\n      start_period: 30s\n    networks:\n      - metrics\n      - backend\n'
}
