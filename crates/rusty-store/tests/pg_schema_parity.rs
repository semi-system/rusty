const KNOWN_DIFFS: &[(&str, &str, &str)] = &[
    // jsonb type replaces the json_valid() CHECK of config columns
    ("sqlite", "CHECKS accounts 3", "accounts.config: jsonb replaces json_valid CHECK (PG 2)"),
    ("pg", "CHECKS accounts 2", "see above"),
    ("sqlite", "CHECKS domains 2", "domains.config: jsonb replaces json_valid CHECK (PG 1)"),
    ("pg", "CHECKS domains 1", "see above"),
    ("sqlite", "CHECKS plans 2", "plans.config: jsonb replaces json_valid CHECK (PG 1)"),
    ("pg", "CHECKS plans 1", "see above"),
    // blobs: SQLite 4 checks (hash glob, size, refcount, zero_since>=0); PG 4 + consistency
    ("sqlite", "CHECKS blobs 4", "PG adds blobs_zero_since_consistent (refcount=0 <=> zero_since set)"),
    ("pg", "CHECKS blobs 5", "see above"),
    // 32-byte hashes are bytea in PG, 64-char hex TEXT in SQLite (public BlobHash stays hex)
    ("sqlite", "COL blobs.hash type=TEXT notnull=Y default=", "bytea in PG"),
    ("pg", "COL blobs.hash type=BLOB notnull=Y default=", "bytea in PG"),
    ("sqlite", "COL deliveries.blob_hash type=TEXT notnull=Y default=", "bytea in PG"),
    ("pg", "COL deliveries.blob_hash type=BLOB notnull=Y default=", "bytea in PG"),
    ("sqlite", "COL messages.blob_hash type=TEXT notnull=Y default=", "bytea in PG"),
    ("pg", "COL messages.blob_hash type=BLOB notnull=Y default=", "bytea in PG"),
    // list_members.seq: nullable in SQLite (ADD COLUMN + AFTER INSERT fill); NOT NULL in PG,
    // filled by a BEFORE INSERT trigger, so list_members_seq_upd has no PG counterpart
    ("sqlite", "COL list_members.seq type=INTEGER notnull=N default=", "PG: NOT NULL + BEFORE INSERT trigger"),
    ("pg", "COL list_members.seq type=INTEGER notnull=Y default=", "see above"),
    ("sqlite", "TRIGGER list_members_seq_upd", "replaced by the NOT NULL constraint"),
    // zero_since: two SQLite AFTER UPDATE triggers become one PG BEFORE trigger
    ("sqlite", "TRIGGER blobs_zero_since_referenced", "merged into blobs_zero_since_refcount"),
    ("sqlite", "TRIGGER blobs_zero_since_released", "merged into blobs_zero_since_refcount"),
    ("pg", "TRIGGER blobs_zero_since_refcount", "merges the two SQLite triggers"),
    // Claim probes (PG5 review I3): Postgres uses two ordered partial indexes instead of (state, run_after)
    ("sqlite", "INDEX jobs_state_run_after on jobs (state,run_after) unique=false partial=false", "PG: partial jobs_queued_order / jobs_running_lease"),
    ("pg", "INDEX jobs_queued_order on jobs (run_after,id) unique=false partial=true", "see above"),
    ("pg", "INDEX jobs_running_lease on jobs (lease_expires_at) unique=false partial=true", "see above"),
    // PG splits "BEFORE UPDATE" vs "BEFORE DELETE" releases and guards TRUNCATE
    ("pg", "TRIGGER accounts_addr_unique_del", "SQLite releases via the registry-less rule; PG registry needs explicit release"),
    ("pg", "TRIGGER aliases_addr_unique_del", "see above"),
    ("pg", "TRIGGER lists_addr_unique_del", "see above"),
    ("pg", "TRIGGER accounts_addr_truncate", "registry hygiene on TRUNCATE"),
    ("pg", "TRIGGER aliases_addr_truncate", "see above"),
    ("pg", "TRIGGER lists_addr_truncate", "see above"),
];

fn normalize_default(d: &str) -> String {
    let d = d.split("::").next().unwrap_or(d);
    d.trim().trim_matches('(').trim_matches(')').to_owned()
}

fn class_of_pg(t: &str) -> &'static str {
    match t {
        "bigint" => "INTEGER",
        "text" | "jsonb" => "TEXT",
        "bytea" => "BLOB",
        other => panic!("unmapped pg type {other}"),
    }
}

async fn sqlite_description(s: &SqlitePool) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let tables: Vec<String> = sqlx::query_scalar(
        "SELECT name FROM sqlite_master WHERE type='table' \
         AND name NOT LIKE 'sqlite_%' AND name <> '_sqlx_migrations'",
    )
    .fetch_all(s)
    .await
    .unwrap();
    // primary keys first (needed to resolve implicit FK targets)
    let mut pks = std::collections::BTreeMap::new();
    for t in &tables {
        let cols: Vec<(String, String, i64, Option<String>, i64)> = sqlx::query_as(&format!(
            "SELECT name, type, \"notnull\", dflt_value, pk FROM pragma_table_info('{t}') ORDER BY cid"
        ))
        .fetch_all(s)
        .await
        .unwrap();
        let mut pk: Vec<(i64, String)> = cols
            .iter()
            .filter(|c| c.4 > 0)
            .map(|c| (c.4, c.0.clone()))
            .collect();
        pk.sort();
        let pk: Vec<String> = pk.into_iter().map(|(_, n)| n).collect();
        for (name, ty, notnull, dflt, pkpos) in &cols {
            let nn = if *notnull == 1 || *pkpos > 0 { "Y" } else { "N" };
            out.insert(format!(
                "COL {t}.{name} type={ty} notnull={nn} default={}",
                dflt.as_deref().map(normalize_default).unwrap_or_default()
            ));
        }
        if !pk.is_empty() {
            out.insert(format!("PK {t} ({})", pk.join(",")));
        }
        pks.insert(t.clone(), pk);
        let sql: String = sqlx::query_scalar("SELECT sql FROM sqlite_master WHERE name=?")
            .bind(t)
            .fetch_one(s)
            .await
            .unwrap();
        let checks = sql.to_uppercase().matches("CHECK").count();
        out.insert(format!("CHECKS {t} {checks}"));
    }
    for t in &tables {
        let idx: Vec<(String, i64, String, i64)> = sqlx::query_as(&format!(
            "SELECT name, \"unique\", origin, partial FROM pragma_index_list('{t}')"
        ))
        .fetch_all(s)
        .await
        .unwrap();
        for (name, unique, origin, partial) in idx {
            if origin == "pk" {
                continue;
            }
            let cols: Vec<Option<String>> = sqlx::query_scalar(&format!(
                "SELECT name FROM pragma_index_info('{name}') ORDER BY seqno"
            ))
            .fetch_all(s)
            .await
            .unwrap();
            let expr = cols.iter().any(Option::is_none);
            let cols: Vec<String> = cols
                .into_iter()
                .map(|c| c.unwrap_or_else(|| "<expr>".into()))
                .collect();
            if unique == 1 && partial == 0 && !expr {
                out.insert(format!("UNIQUE {t} ({})", cols.join(",")));
            } else {
                out.insert(format!(
                    "INDEX {name} on {t} ({}) unique={} partial={}",
                    cols.join(","),
                    unique == 1,
                    partial == 1
                ));
            }
        }
        let fks: Vec<(i64, String, Option<String>, String, String)> = sqlx::query_as(&format!(
            "SELECT id, \"table\", \"to\", \"from\", on_delete FROM pragma_foreign_key_list('{t}') ORDER BY id, seq"
        ))
        .fetch_all(s)
        .await
        .unwrap();
        let mut grouped: std::collections::BTreeMap<i64, (String, Vec<String>, Vec<Option<String>>, String)> =
            Default::default();
        for (id, target, to, from, on_delete) in fks {
            let e = grouped
                .entry(id)
                .or_insert((target, vec![], vec![], on_delete));
            e.1.push(from);
            e.2.push(to);
        }
        for (_, (target, from, to, on_delete)) in grouped {
            let to: Vec<String> = if to.iter().all(Option::is_none) {
                pks[&target].clone()
            } else {
                to.into_iter().map(Option::unwrap).collect()
            };
            out.insert(format!(
                "FK {t} ({}) -> {target} ({}) on_delete={on_delete}",
                from.join(","),
                to.join(",")
            ));
        }
    }
    let triggers: Vec<String> =
        sqlx::query_scalar("SELECT name FROM sqlite_master WHERE type='trigger'")
            .fetch_all(s)
            .await
            .unwrap();
    for t in triggers {
        out.insert(format!("TRIGGER {t}"));
    }
    out
}

async fn pg_description(p: &PgPool) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let cols: Vec<(String, String, String, String, Option<String>, String)> = sqlx::query_as(
        "SELECT table_name, column_name, data_type, is_nullable, column_default, is_identity \
         FROM information_schema.columns WHERE table_schema='public' \
           AND table_name <> '_sqlx_migrations' AND table_name <> 'address_owners'",
    )
    .fetch_all(p)
    .await
    .unwrap();
    for (t, c, ty, nullable, default, identity) in cols {
        let default = if identity == "YES" {
            String::new()
        } else {
            default.as_deref().map(normalize_default).unwrap_or_default()
        };
        let nn = if nullable == "NO" { "Y" } else { "N" };
        out.insert(format!(
            "COL {t}.{c} type={} notnull={nn} default={default}",
            class_of_pg(&ty)
        ));
    }
    let cons: Vec<(String, String, String, Vec<String>, Option<String>, Option<Vec<String>>, String)> =
        sqlx::query_as(
            "SELECT c.conrelid::regclass::text, c.contype::text, c.conname, \
                    ARRAY(SELECT a.attname::text FROM unnest(c.conkey) WITH ORDINALITY k(n,o) \
                          JOIN pg_attribute a ON a.attrelid=c.conrelid AND a.attnum=k.n ORDER BY k.o), \
                    c.confrelid::regclass::text, \
                    ARRAY(SELECT a.attname::text FROM unnest(c.confkey) WITH ORDINALITY k(n,o) \
                          JOIN pg_attribute a ON a.attrelid=c.confrelid AND a.attnum=k.n ORDER BY k.o), \
                    c.confdeltype::text \
             FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace \
             WHERE n.nspname='public' AND c.conrelid::regclass::text NOT IN ('_sqlx_migrations','address_owners')",
        )
        .fetch_all(p)
        .await
        .unwrap();
    let mut checks: std::collections::BTreeMap<String, usize> = Default::default();
    for (t, kind, _name, cols, target, tcols, deltype) in cons {
        match kind.as_str() {
            "p" => {
                out.insert(format!("PK {t} ({})", cols.join(",")));
            }
            "u" => {
                out.insert(format!("UNIQUE {t} ({})", cols.join(",")));
            }
            "n" => {}
            "c" => *checks.entry(t).or_default() += 1,
            "f" => {
                let action = match deltype.as_str() {
                    "a" => "NO ACTION",
                    "r" => "RESTRICT",
                    "c" => "CASCADE",
                    "n" => "SET NULL",
                    _ => "SET DEFAULT",
                };
                out.insert(format!(
                    "FK {t} ({}) -> {} ({}) on_delete={action}",
                    cols.join(","),
                    target.unwrap(),
                    tcols.unwrap().join(",")
                ));
            }
            other => panic!("unexpected constraint kind {other}"),
        }
    }
    let tables: Vec<String> = sqlx::query_scalar(
        "SELECT table_name FROM information_schema.tables WHERE table_schema='public' \
         AND table_type='BASE TABLE' AND table_name NOT IN ('_sqlx_migrations','address_owners')",
    )
    .fetch_all(p)
    .await
    .unwrap();
    for t in tables {
        out.insert(format!("CHECKS {t} {}", checks.get(&t).copied().unwrap_or(0)));
    }
    // Indexes that do not back a constraint, plus unique indexes that are not plain.
    let idx: Vec<(String, String, bool, bool, Vec<String>)> = sqlx::query_as(
        "SELECT t.relname::text, i.relname::text, ix.indisunique, ix.indpred IS NOT NULL, \
                ARRAY(SELECT CASE WHEN k.n = 0 THEN '<expr>' ELSE a.attname::text END \
                      FROM unnest(ix.indkey::int2[]) WITH ORDINALITY k(n,o) \
                      LEFT JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=k.n ORDER BY k.o) \
         FROM pg_index ix JOIN pg_class t ON t.oid=ix.indrelid JOIN pg_class i ON i.oid=ix.indexrelid \
         JOIN pg_namespace n ON n.oid=t.relnamespace \
         WHERE n.nspname='public' AND t.relname NOT IN ('_sqlx_migrations','address_owners') \
           AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid=ix.indexrelid)",
    )
    .fetch_all(p)
    .await
    .unwrap();
    for (t, name, unique, partial, cols) in idx {
        let expr = cols.iter().any(|c| c == "<expr>");
        if unique && !partial && !expr {
            out.insert(format!("UNIQUE {t} ({})", cols.join(",")));
        } else {
            out.insert(format!(
                "INDEX {name} on {t} ({}) unique={unique} partial={partial}",
                cols.join(",")
            ));
        }
    }
    let triggers: Vec<String> = sqlx::query_scalar(
        "SELECT t.tgname::text FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid \
         JOIN pg_namespace n ON n.oid=c.relnamespace \
         WHERE n.nspname='public' AND NOT t.tgisinternal AND c.relname <> 'address_owners'",
    )
    .fetch_all(p)
    .await
    .unwrap();
    for t in triggers {
        out.insert(format!("TRIGGER {t}"));
    }
    out
}

#[tokio::test]
async fn pg_schema_matches_sqlite_structure() {
    let Some(admin_url) = pg_admin_url() else {
        return;
    };
    let db = PgTestDb::create(&admin_url).await;
    let pg = db.connect().await;
    let sqlite = SqliteStore::open("sqlite::memory:").await.unwrap();

    let s = sqlite_description(sqlite.pool()).await;
    let p = pg_description(pg.pool()).await;
    let mut sqlite_only: BTreeSet<String> = s.difference(&p).cloned().collect();
    let mut pg_only: BTreeSet<String> = p.difference(&s).cloned().collect();

    let mut unused = vec![];
    for (side, entry, reason) in KNOWN_DIFFS {
        let set = if *side == "sqlite" {
            &mut sqlite_only
        } else {
            &mut pg_only
        };
        if !set.remove(*entry) {
            unused.push(format!("{side}: {entry} ({reason})"));
        }
    }
    let mut report = String::new();
    for e in &sqlite_only {
        report.push_str(&format!("  sqlite-only: {e}\n"));
    }
    for e in &pg_only {
        report.push_str(&format!("  pg-only:     {e}\n"));
    }
    for e in &unused {
        report.push_str(&format!("  stale KNOWN_DIFFS entry: {e}\n"));
    }
    assert!(report.is_empty(), "schema parity differences:\n{report}");

    // The registry table is the one PG-only table (see the migration header).
    let tables: BTreeSet<String> = sqlx::query_scalar(
        "SELECT table_name FROM information_schema.tables WHERE table_schema='public' \
         AND table_type='BASE TABLE' AND table_name <> '_sqlx_migrations'",
    )
    .fetch_all(pg.pool())
    .await
    .unwrap()
    .into_iter()
    .collect();
    assert!(tables.contains("address_owners"));

    pg.close().await;
    db.cleanup().await;
}

#[tokio::test]
async fn rs_now_uses_the_statement_clock() {
    let Some(admin_url) = pg_admin_url() else {
        return;
    };
    let db = PgTestDb::create(&admin_url).await;
    let store = db.connect().await;
    let mut tx = store.begin_write().await.unwrap();
    let first: i64 = sqlx::query_scalar("SELECT rs_now()")
        .fetch_one(&mut *tx)
        .await
        .unwrap();
    tokio::time::sleep(Duration::from_millis(1_200)).await;
    let second: i64 = sqlx::query_scalar("SELECT rs_now()")
        .fetch_one(&mut *tx)
        .await
        .unwrap();
    assert!(second > first, "rs_now stayed at transaction start time");
    let wall = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_secs() as i64;
    assert!(
        (wall - 5..=wall + 5).contains(&second),
        "rs_now() is not unix seconds: {second} vs {wall}"
    );
    tx.rollback().await.unwrap();
    store.close().await;
    db.cleanup().await;
}
