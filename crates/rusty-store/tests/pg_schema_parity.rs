#![cfg(feature = "postgres")]

mod common;

use std::collections::BTreeSet;
use std::path::PathBuf;
use std::time::Duration;

use common::pg::{pg_admin_url, PgTestDb};
use rusty_store::{PgStore, SqliteStore};

fn snapshot_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/snapshots/pg_catalog.snap")
}

async fn catalog_dump(store: &PgStore) -> String {
    let p = store.pool();
    let columns: Vec<(String, String, String, String, String, String)> = sqlx::query_as(
        "SELECT table_name, column_name, data_type, is_nullable, is_identity, \
                COALESCE(column_default, '') \
         FROM information_schema.columns \
         WHERE table_schema='public' AND table_name <> '_sqlx_migrations' \
         ORDER BY table_name, ordinal_position",
    )
    .fetch_all(p)
    .await
    .unwrap();
    let constraints: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT c.conrelid::regclass::text, c.conname, pg_get_constraintdef(c.oid, true) \
         FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace \
         WHERE n.nspname='public' AND c.conrelid <> 0 \
           AND c.conrelid::regclass::text <> '_sqlx_migrations' \
         ORDER BY 1,2",
    )
    .fetch_all(p)
    .await
    .unwrap();
    let indexes: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT tablename,indexname,indexdef FROM pg_indexes \
         WHERE schemaname='public' AND tablename <> '_sqlx_migrations' ORDER BY 1,2",
    )
    .fetch_all(p)
    .await
    .unwrap();
    let triggers: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT c.relname,t.tgname,pg_get_triggerdef(t.oid,true) \
         FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid \
         JOIN pg_namespace n ON n.oid=c.relnamespace \
         WHERE n.nspname='public' AND NOT t.tgisinternal ORDER BY 1,2",
    )
    .fetch_all(p)
    .await
    .unwrap();

    let mut out = String::from(
        "# Generated by pg_schema_parity.rs. Regenerate with RUSTY_UPDATE_PG_SNAPSHOT=1.\n",
    );
    for (table, column, ty, nullable, identity, default) in columns {
        out.push_str(&format!(
            "COLUMN {table}.{column} {ty} nullable={nullable} identity={identity} default={default}\n"
        ));
    }
    for (table, name, definition) in constraints {
        out.push_str(&format!("CONSTRAINT {table}.{name} {definition}\n"));
    }
    for (table, name, definition) in indexes {
        out.push_str(&format!("INDEX {table}.{name} {definition}\n"));
    }
    for (table, name, definition) in triggers {
        out.push_str(&format!("TRIGGER {table}.{name} {definition}\n"));
    }
    out
}

#[tokio::test]
async fn pg_catalog_matches_snapshot_and_sqlite_table_set() {
    let Some(admin_url) = pg_admin_url() else {
        return;
    };
    let db = PgTestDb::create(&admin_url).await;
    let pg = db.connect().await;
    let got = catalog_dump(&pg).await;
    let path = snapshot_path();
    if std::env::var("RUSTY_UPDATE_PG_SNAPSHOT").as_deref() == Ok("1") {
        std::fs::write(&path, &got).unwrap();
    } else {
        let want = std::fs::read_to_string(&path).unwrap_or_else(|e| {
            panic!(
                "cannot read {} ({e}); regenerate with RUSTY_UPDATE_PG_SNAPSHOT=1",
                path.display()
            )
        });
        assert_eq!(
            got, want,
            "Postgres catalog differs from committed snapshot"
        );
    }

    let mut pg_tables: BTreeSet<String> = sqlx::query_scalar(
        "SELECT table_name FROM information_schema.tables \
         WHERE table_schema='public' AND table_type='BASE TABLE' \
           AND table_name <> '_sqlx_migrations'",
    )
    .fetch_all(pg.pool())
    .await
    .unwrap()
    .into_iter()
    .collect();
    // PostgreSQL needs one physical registry to make uniqueness across three owner tables
    // concurrency-safe. It is an implementation detail, not a domain-model difference.
    assert!(pg_tables.remove("address_owners"));

    let sqlite = SqliteStore::open("sqlite::memory:").await.unwrap();
    let sqlite_tables: BTreeSet<String> = sqlx::query_scalar(
        "SELECT name FROM sqlite_master WHERE type='table' \
         AND name NOT LIKE 'sqlite_%' AND name <> '_sqlx_migrations'",
    )
    .fetch_all(sqlite.pool())
    .await
    .unwrap()
    .into_iter()
    .collect();
    assert_eq!(pg_tables, sqlite_tables);

    pg.close().await;
    db.cleanup().await;
}

#[tokio::test]
async fn rs_now_uses_the_statement_clock() {
    let Some(admin_url) = pg_admin_url() else {
        return;
    };
    let db = PgTestDb::create(&admin_url).await;
    let store = db.connect().await;
    let mut tx = store.begin_write().await.unwrap();
    let first: i64 = sqlx::query_scalar("SELECT rs_now()")
        .fetch_one(&mut *tx)
        .await
        .unwrap();
    tokio::time::sleep(Duration::from_millis(1_200)).await;
    let second: i64 = sqlx::query_scalar("SELECT rs_now()")
        .fetch_one(&mut *tx)
        .await
        .unwrap();
    assert!(second > first, "rs_now stayed at transaction start time");
    tx.rollback().await.unwrap();
    store.close().await;
    db.cleanup().await;
}
