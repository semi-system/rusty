//! Postgres schema parity.
//!
//! 1. `pg_schema_matches_sqlite_structure` is the real parity test. It extracts a normalized
//!    description from the SQLite catalog (pragma_table_info / index_list / foreign_key_list,
//!    sqlite_master) and from the Postgres catalog and compares them: tables, columns (name,
//!    NOT NULL, type class, default), primary keys, UNIQUE sets, non-unique / partial / expression
//!    indexes (by name), foreign keys (columns, target, ON DELETE action), CHECK counts per table
//!    and trigger names. Every deliberate difference is listed in `KNOWN_DIFFS` with its reason; a
//!    difference that is not listed fails, and a listed one that no longer occurs fails too.
//!    CHECK expressions and trigger/function bodies are NOT translated and compared textually (the
//!    dialects differ); they are covered behaviourally by pg_schema_cases.rs.
//! 2. `pg_catalog_matches_snapshot` is a change detector over the Postgres catalog including
//!    function bodies, identity generation and column collations. It is generated from Postgres
//!    itself, so it is NOT an oracle: a regenerated snapshot blesses whatever is in the migration.
//!    Regenerate with RUSTY_UPDATE_PG_SNAPSHOT=1 and review the diff.
//!
//! backend-neutral: Postgres-only suite (needs a server; compares against the SQLite behaviour elsewhere)

#![cfg(feature = "postgres")]
#![allow(clippy::type_complexity)]

mod common;

use std::collections::BTreeSet;
use std::path::PathBuf;
