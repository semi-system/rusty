fn snapshot_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/snapshots/pg_catalog.snap")
}

/// Rows are ordered with COLLATE "C" so the snapshot does not depend on the server locale.
async fn catalog_dump(store: &PgStore) -> String {
    let p = store.pool();
    let columns: Vec<(String, String, String, String, String, String, String, String)> = sqlx::query_as(
        "SELECT table_name, column_name, data_type, is_nullable, is_identity, \
                COALESCE(identity_generation, ''), COALESCE(column_default, ''), \
                COALESCE(collation_name, '') \
         FROM information_schema.columns \
         WHERE table_schema='public' AND table_name <> '_sqlx_migrations' \
         ORDER BY table_name COLLATE \"C\", ordinal_position",
    )
    .fetch_all(p)
    .await
    .unwrap();
    let constraints: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT c.conrelid::regclass::text, c.conname, pg_get_constraintdef(c.oid, true) \
         FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace \
         WHERE n.nspname='public' AND c.conrelid <> 0 \
           AND c.conrelid::regclass::text <> '_sqlx_migrations' \
         ORDER BY c.conrelid::regclass::text COLLATE \"C\", c.conname COLLATE \"C\"",
    )
    .fetch_all(p)
    .await
    .unwrap();
    let indexes: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT tablename,indexname,indexdef FROM pg_indexes \
         WHERE schemaname='public' AND tablename <> '_sqlx_migrations' \
         ORDER BY tablename COLLATE \"C\", indexname COLLATE \"C\"",
    )
    .fetch_all(p)
    .await
    .unwrap();
    let triggers: Vec<(String, String, String)> = sqlx::query_as(
        "SELECT c.relname,t.tgname,pg_get_triggerdef(t.oid,true) \
         FROM pg_trigger t JOIN pg_class c ON c.oid=t.tgrelid \
         JOIN pg_namespace n ON n.oid=c.relnamespace \
         WHERE n.nspname='public' AND NOT t.tgisinternal \
         ORDER BY c.relname COLLATE \"C\", t.tgname COLLATE \"C\"",
    )
    .fetch_all(p)
    .await
    .unwrap();
    // Function bodies: pg_get_triggerdef only shows the function name.
    let functions: Vec<(String, String)> = sqlx::query_as(
        "SELECT p.proname, pg_get_functiondef(p.oid) FROM pg_proc p \
         JOIN pg_namespace n ON n.oid=p.pronamespace \
         WHERE n.nspname='public' ORDER BY p.proname COLLATE \"C\"",
    )
    .fetch_all(p)
    .await
    .unwrap();

    let mut out = String::from(
        "# Generated by pg_schema_parity.rs. Regenerate with RUSTY_UPDATE_PG_SNAPSHOT=1.\n\
         # Change detector only (generated from Postgres itself); see the test's module docs.\n",
    );
    for (table, column, ty, nullable, identity, generation, default, collation) in columns {
        out.push_str(&format!(
            "COLUMN {table}.{column} {ty} nullable={nullable} identity={identity}/{generation} collation={collation} default={default}\n"
        ));
    }
    for (table, name, definition) in constraints {
        out.push_str(&format!("CONSTRAINT {table}.{name} {definition}\n"));
    }
    for (table, name, definition) in indexes {
        out.push_str(&format!("INDEX {table}.{name} {definition}\n"));
    }
    for (table, name, definition) in triggers {
        out.push_str(&format!("TRIGGER {table}.{name} {definition}\n"));
    }
    for (name, definition) in functions {
        out.push_str(&format!("FUNCTION {name}\n{}\n", definition.trim_end()));
    }
    out
}

/// Line-level summary of what regenerating the snapshot changes: counts plus the first changed
/// lines of each side.
fn snapshot_diff_summary(old: &str, new: &str) -> String {
    let o: BTreeSet<&str> = old.lines().collect();
    let n: BTreeSet<&str> = new.lines().collect();
    let removed: Vec<&&str> = o.difference(&n).collect();
    let added: Vec<&&str> = n.difference(&o).collect();
    let mut s = format!(
        "RUSTY_UPDATE_PG_SNAPSHOT=1: snapshot regenerated, {} lines removed, {} lines added",
        removed.len(),
        added.len()
    );
    for l in removed.iter().take(40) {
        s.push_str(&format!("
  - {}", l.chars().take(160).collect::<String>()));
    }
    for l in added.iter().take(40) {
        s.push_str(&format!("
  + {}", l.chars().take(160).collect::<String>()));
    }
    if removed.len() + added.len() == 0 {
        s.push_str(" (no change)");
    }
    s
}

// backend-neutral: unit test of the snapshot diff summary, no database
#[test]
fn snapshot_regeneration_prints_a_diff_summary() {
    let s = snapshot_diff_summary("A
B
C
", "A
C
D
E
");
    assert!(s.contains("1 lines removed, 2 lines added"), "{s}");
    assert!(s.contains("  - B") && s.contains("  + D") && s.contains("  + E"), "{s}");
    assert!(snapshot_diff_summary("A
", "A
").contains("(no change)"));
}

#[tokio::test]
async fn pg_catalog_matches_snapshot() {
    let Some(admin_url) = pg_admin_url() else {
        return;
    };
    let db = PgTestDb::create(&admin_url).await;
    let pg = db.connect().await;
    let got = catalog_dump(&pg).await;
    let path = snapshot_path();
    if std::env::var("RUSTY_UPDATE_PG_SNAPSHOT").as_deref() == Ok("1") {
        // Regenerating blesses whatever the migration says, so it is loud: the summary below is
        // what a reviewer reads in the log, and CI never sets the variable.
        let old = std::fs::read_to_string(&path).unwrap_or_default();
        eprintln!("{}", snapshot_diff_summary(&old, &got));
        std::fs::write(&path, &got).unwrap();
    } else {
        let want = std::fs::read_to_string(&path).unwrap_or_else(|e| {
            panic!(
                "cannot read {} ({e}); regenerate with RUSTY_UPDATE_PG_SNAPSHOT=1",
                path.display()
            )
        });
        assert_eq!(got, want, "Postgres catalog differs from committed snapshot");
    }
    pg.close().await;
    db.cleanup().await;
}

