//! Schema snapshot: the schema produced by all migrations on a fresh database must match the
//! committed `tests/snapshots/schema.sql.snap` exactly.
//!
//! The snapshot lists every table, index and trigger from `sqlite_master` (sqlx's own
//! `_sqlx_migrations` table and SQLite's internal `sqlite_*` objects excluded), sorted by
//! type then name, with SQL comments removed and whitespace collapsed. It is also the
//! baseline the future Postgres schema-equivalence test compares against.
//!
//! A deliberate schema change regenerates it:
//!
//!     RUSTY_UPDATE_SNAPSHOT=1 cargo test -p rusty-store --test schema_snapshot
//!
//! and the regenerated file is reviewed and committed together with the migration.

use std::path::PathBuf;

use rusty_store::SqliteStore;

fn snapshot_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/snapshots/schema.sql.snap")
}

/// Drop `--` comments (the schema has no string literals containing `--`), collapse every
/// whitespace run to one space, trim.
fn normalize(sql: &str) -> String {
    let no_comments: Vec<&str> = sql
        .lines()
        .map(|l| l.find("--").map_or(l, |i| &l[..i]))
        .collect();
    no_comments
        .join("\n")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

async fn dump() -> String {
    let store = SqliteStore::open("sqlite::memory:").await.unwrap();
    let rows: Vec<(String, String, String, Option<String>)> = sqlx::query_as(
        "SELECT type, name, tbl_name, sql FROM sqlite_master \
         WHERE name NOT LIKE 'sqlite_%' AND name <> '_sqlx_migrations' \
         ORDER BY type, name",
    )
    .fetch_all(store.pool())
    .await
    .unwrap();
    let mut out = String::from(
        "-- Generated by crates/rusty-store/tests/schema_snapshot.rs; do not edit by hand.\n\
         -- Regenerate: RUSTY_UPDATE_SNAPSHOT=1 cargo test -p rusty-store --test schema_snapshot\n",
    );
    for (ty, name, tbl, sql) in rows {
        out.push_str(&format!("\n-- {ty} {name} on {tbl}\n"));
        out.push_str(&normalize(sql.as_deref().unwrap_or("")));
        out.push_str(";\n");
    }
    out
}

// backend-neutral: SQLite schema snapshot; the Postgres counterpart is pg_schema_parity.rs against the SQLite catalog
#[tokio::test]
async fn schema_matches_snapshot() {
    let got = dump().await;
    let path = snapshot_path();
    if std::env::var("RUSTY_UPDATE_SNAPSHOT").as_deref() == Ok("1") {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &got).unwrap();
        eprintln!("schema snapshot written to {}", path.display());
        return;
    }
    let want = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "cannot read {} ({e}); generate it with RUSTY_UPDATE_SNAPSHOT=1",
            path.display()
        )
    });
    if got != want {
        let first = got
            .lines()
            .zip(want.lines())
            .position(|(g, w)| g != w)
            .unwrap_or_else(|| got.lines().count().min(want.lines().count()));
        panic!(
            "schema differs from {} (first difference at line {}):\n  got:  {:?}\n  want: {:?}\n\
             If the change is deliberate, regenerate with RUSTY_UPDATE_SNAPSHOT=1 and commit it.",
            path.display(),
            first + 1,
            got.lines().nth(first),
            want.lines().nth(first),
        );
    }
}

// backend-neutral: SQLite schema snapshot; the Postgres counterpart is pg_schema_parity.rs against the SQLite catalog
#[test]
fn normalize_strips_comments_and_whitespace() {
    assert_eq!(
        normalize("CREATE TABLE t (\n  a INTEGER, -- note\n  b   TEXT\n)"),
        "CREATE TABLE t ( a INTEGER, b TEXT )"
    );
}
